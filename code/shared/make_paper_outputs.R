#  Status ledger: one row per deliverable, printed in the final recap.
.status <- data.table(item = character(), status = character())
mark <- function(item, ok) {
  .status <<- rbind(.status,
                    data.table(item = item, status = if (ok) "ok" else "MISSING"))
  invisible(ok)
}

copy_fig <- function(src, dst_dir, dst_name = basename(src)) {
  ok <- file.exists(src)
  if (ok) file.copy(src, file.path(dst_dir, dst_name), overwrite = TRUE)
  mark(file.path(basename(dst_dir), dst_name), ok)
}

fmt <- function(x, d = 3) formatC(x, format = "f", digits = d)

#  Numbers ledger: every scalar quoted in the text of the paper.
.numbers <- data.table(name = character(), value = numeric())
add_number <- function(name, value) {
  .numbers <<- rbind(.numbers,
                     data.table(name = name, value = as.numeric(value)))
  invisible(value)
}

