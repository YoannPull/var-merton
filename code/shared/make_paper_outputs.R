# =============================================================================
#  code/shared/make_paper_outputs.R
#
#  PAPER REPLICATION: assembles every figure and table included in the paper,
#  with the exact file names referenced by the LaTeX source, into
#
#      output/paper_replication/
#        figures/main/                    (11 figures of the main text)
#        figures/robustness/<spec>/       (6 figures of the robustness appendix)
#        tables/                          (6 LaTeX tables)
#        paper_numbers.csv                (every scalar quoted in the text)
#
#  To compile the paper, copy output/paper_replication/figures/ next to the
#  .tex file (the LaTeX includes use the relative paths figures/main/... and
#  figures/robustness/...).
#
#  PREREQUISITES (in order; all are steps of run_all.R):
#    1. code/01_process_gpr.R, code/02_build_dataset.R          (data)
#    2. code/dralacbn/02_dralacbn_information_set_robustness.R  (main + robustness)
#    3. code/dralacbn/08_dralacbn_perfect_foresight.R           (Section 3.4)
#    4. code/dralacbn/10_dralacbn_state_dependence.R            (Section 3.3)
#  This script is idempotent and purely assembles existing outputs; the only
#  computation it performs is the derivation of in-text scalars (e.g. the
#  posterior probability of a positive peak response) from saved draws.
#
#  Every missing input is reported and skipped; the final recap lists what was
#  produced and what is still missing.
#
#  Run from the repository root:
#      source("code/shared/make_paper_outputs.R")
# =============================================================================

