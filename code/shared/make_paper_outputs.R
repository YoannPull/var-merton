#  Pretty satellite term names, aligned with the paper tables.
pretty_sat_term <- function(variable) {
  v <- gsub("Investment \\(p\\.c\\., log\\)", "Investment (p.c., log)", variable)
  v
}

#  Generator for the model-averaged satellite tables (Table 2 and the full
#  appendix table), built from the averaged_regression.csv of the pipeline.
write_bma_table <- function(csv_path, out_path, caption, label,
                            min_inclusion = 0, footer = list()) {
  if (!file.exists(csv_path)) return(mark(basename(out_path), FALSE))
  tab <- fread(csv_path)
  keep <- tab$term == "(Intercept)" | tab$inclusion_prob >= min_inclusion
  tab <- tab[keep]

  con <- tex_open(out_path); on.exit(close(con), add = TRUE)
  cat("\\begin{table}[!htbp]\n\\centering\n\\scriptsize\n", file = con)
  cat("\\caption{\\textbf{", caption, "}}\n", sep = "", file = con)
  cat("\\label{", label, "}\n", sep = "", file = con)
  cat("\\begin{tabular}{lcccc}\n\\toprule\n", file = con)
  cat("Variable & Coef. & Post. SD & 90\\% CI & Incl. prob. \\\\\n\\midrule\n",
      file = con)
  for (i in seq_len(nrow(tab))) {
    stars <- if (nzchar(tab$signif[i])) paste0("$^{", gsub("\\*", "*", tab$signif[i]), "}$") else ""
    cat(pretty_sat_term(tab$variable[i]), " & $",
        fmt(tab$post_mean[i], 4), stars, "$ & ",
        fmt(tab$post_sd[i], 4), " & $[",
        fmt(tab$q05[i], 4), ",\\ ", fmt(tab$q95[i], 4), "]$ & ",
        fmt(tab$inclusion_prob[i], 2), " \\\\\n",
        sep = "", file = con)
  }
  if (length(footer)) {
    cat("\\midrule\n", file = con)
    for (nm in names(footer)) {
      cat(nm, " & \\multicolumn{4}{r}{", footer[[nm]], "} \\\\\n",
          sep = "", file = con)
    }
  }
  cat("\\bottomrule\n\\end{tabular}\n", file = con)
  cat("\\begin{tablenotes}\n\\footnotesize\n", file = con)
  cat("\\item Notes: Posterior mean, standard deviation, and 90\\% credible",
      " interval of each satellite coefficient under Schwarz (BIC) model",
      " averaging. The inclusion probability is the cumulative weight of the",
      " retained models that contain the term. Stars $^{*}$/$^{**}$/$^{***}$",
      " denote a posterior probability of the coefficient sign exceeding",
      " $0.95$/$0.975$/$0.99$.\n", sep = "", file = con)
  cat("\\end{tablenotes}\n\\end{table}\n", file = con)
  mark(basename(out_path), TRUE)
}

